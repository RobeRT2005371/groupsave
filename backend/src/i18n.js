export const isLang = (c) => LANG_CODES.includes(c);

export function t(lang, key, vars = {}) {
  const str = S[lang]?.[key] ?? S.en[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

/** "Choose language" screen shown to everyone, with each language written in its own name. */
export const languageMenu = () => 'Language / Ululimi:\n' + LANGUAGES.map((l, i) => `${i + 1}. ${l.name}`).join('\n');
export const langFromChoice = (c) => LANGUAGES[Number(c) - 1]?.code;

export function smsBody(lang, { type, reversal, amountText, totalText, date, id, code }) {
  const label = t(lang, type) + (reversal ? ` (${t(lang, 'rev')})` : '');
  return t(lang, 'sms', {
    amt: amountText, label, date, total: totalText, id, code,
    totalWord: t(lang, 'totalWord'), refWord: t(lang, 'refWord'), codeWord: t(lang, 'codeWord'),
  });
}
